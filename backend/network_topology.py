# سنسورهای فشار: گره‌های ۲ تا ۳۲ (گره ۱ مخزن است) → ستون‌های n1..n31
SENSOR_NODES = list(range(2, 33))


def nearest_pipe(x: float, y: float):
    """نزدیک‌ترین لوله به نقطه (x,y) + محل تصویر نقطه روی همان لوله"""
    best = None
    for pid, (a, b) in PIPES.items():
        ax, ay = NODES[a]
        bx, by = NODES[b]
        dx, dy = bx - ax, by - ay
        L2 = dx * dx + dy * dy
        if L2 == 0:
            t = 0.0
        else:
            t = max(0.0, min(1.0, ((x - ax) * dx + (y - ay) * dy) / L2))
        px, py = ax + t * dx, ay + t * dy
        d2 = (x - px) ** 2 + (y - py) ** 2
        if best is None or d2 < best["d2"]:
            best = {"pipe": pid, "x": px, "y": py, "t": t, "d2": d2,
                    "node_a": a, "node_b": b}
    return best


def topology_payload():
    return {
        "nodes": [{"id": n, "x": xy[0], "y": xy[1],
                   "is_reservoir": n == RESERVOIR_NODE}
                  for n, xy in NODES.items()],
        "pipes": [{"id": p, "a": ab[0], "b": ab[1]} for p, ab in PIPES.items()],
        "reservoir_head_m": RESERVOIR_HEAD_M,
        "sensor_nodes": SENSOR_NODES,
        "sensor_columns": [f"n{i}" for i in range(1, len(SENSOR_NODES) + 1)],
    }
